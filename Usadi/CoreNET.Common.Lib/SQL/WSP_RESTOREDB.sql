CREATE PROCEDURE [dbo].[WSP_RESTOREDB] 
(@RESTOREDB varchar(300), @BACKUPDB varchar(300), @MDFLDFPATH VARCHAR(300),@DATAFILE VARCHAR(300),@BAKFILE VARCHAR(300) )
AS
DECLARE @LOKASI_MDF VARCHAR(300)
IF @MDFLDFPATH IS NULL OR @MDFLDFPATH = ''
BEGIN
	SET @LOKASI_MDF = 'D:\MSSQL2005\DATA\'
END
ELSE
BEGIN
	SET @LOKASI_MDF = @MDFLDFPATH	
END
IF RIGHT(RTRIM(@LOKASI_MDF),1) <> '\'
BEGIN
	SET @LOKASI_MDF = RTRIM(@LOKASI_MDF) + '\'
END

