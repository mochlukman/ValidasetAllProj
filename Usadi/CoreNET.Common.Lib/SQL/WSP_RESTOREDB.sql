DECLARE @SQLRESTORE NVARCHAR(1000)
SET @SQLRESTORE = '
RESTORE DATABASE ' + @RESTOREDB + '
FROM DISK = ''' + @BACKUPDB + ''' WITH REPLACE, 
MOVE '''+@DATAFILE+''' TO ''' + @LOKASI_MDF + '' + @RESTOREDB + '.MDF'', 
MOVE '''+@BAKFILE+''' TO ''' + @LOKASI_MDF + '' + @RESTOREDB + '.LDF'''
